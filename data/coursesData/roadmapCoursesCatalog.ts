// Helper to quickly look up existing full courses by slug or id
const existingCoursesPool: Course[] = [
  ...PROGRAMMING_LANGUAGES_COURSES,
  ...WEB_DEVELOPMENT_COURSES,
  ...DSA_AND_TOOLS_COURSES,
  ...DATABASES_AND_INFRASTRUCTURE_COURSES,
  ...AI_AND_MACHINE_LEARNING_COURSES,
];

function findExisting(idOrSlug: string): Partial<Course> {
  const norm = idOrSlug.toLowerCase();
  const found = existingCoursesPool.find(
    (c) =>
      c.id.toLowerCase() === norm ||
      c.id.toLowerCase() === `course-${norm}` ||
      c.slug.toLowerCase() === norm ||
      c.aliases?.some((a) => a.toLowerCase() === norm) ||
      c.id.toLowerCase().includes(norm) ||
      c.slug.toLowerCase().includes(norm)
  );
  return found ? { ...found } : {};
}

